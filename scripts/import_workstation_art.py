"""Validate and copy the 90 full-canvas PNGs without modifying artist originals."""
import argparse
import hashlib
import runpy
import shutil
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'src/dzmm_bot/admin/static/workstation'
CORE = ROOT / 'src/dzmm_bot/core'


def import_art(source):
    categories = runpy.run_path(str(CORE / 'workstation_catalog.py'))['CATEGORIES']
    files, digest = [], hashlib.sha256()
    for category in categories:
        key = category['key']
        for level in range(1, 11):
            path = source / key / f'{key}_lv{level:02d}.png'
            data = path.read_bytes()
            with Image.open(path) as image:
                image.load()
                if image.format != 'PNG' or image.size != (1536, 1024) or image.mode != 'RGBA':
                    raise ValueError(f'Expected 1536x1024 RGBA PNG: {path}')
            digest.update(f'{key}/{level}:'.encode())
            digest.update(hashlib.sha256(data).digest())
            files.append((key, level, path, hashlib.sha256(data).hexdigest()))
    revision = digest.hexdigest()[:12]
    names = set()
    ASSETS.mkdir(exist_ok=True)
    for key, level, source_path, expected_hash in files:
        name = f'growth-{revision}-{key}-lv{level:02d}.png'
        target = ASSETS / name
        # A source changed after validation must be revalidated, not silently imported.
        if hashlib.sha256(source_path.read_bytes()).hexdigest() != expected_hash:
            raise ValueError(f'Source changed during import: {source_path}')
        shutil.copyfile(source_path, target)
        if hashlib.sha256(target.read_bytes()).hexdigest() != expected_hash:
            raise ValueError(f'Copy verification failed: {target}')
        names.add(name)
    (CORE / 'workstation_art_assets.py').write_text(
        '"""Generated by scripts/import_workstation_art.py. Do not edit by hand."""\n'
        f'ART_REVISION = "{revision}"\n', encoding='utf-8')
    for path in ASSETS.glob('growth-*.png'):
        if path.name not in names:
            path.unlink()
    print(f'Imported and SHA256-verified {len(files)} PNGs; revision {revision}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    import_art(parser.parse_args().source.resolve())
